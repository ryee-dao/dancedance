/// <reference types="node" />
/**
 * The reviewed genre vocabulary (src/core/choreo/genreVocab.testutil.ts) and
 * what each name maps to with songStyle.ts: the label the owner sees, the
 * leading dance families, sub-style scores, themes, whether it is dance
 * music, its calm hint and usual stepping tempo, and the genre sets it opens
 * on its own (no audio traits). Pure; writes markdown.
 *
 *   npx tsx tools/eval/genreTable.ts > tools/eval/data/genre-vocabulary.md
 */
import { styleGenres } from '../../src/core/choreo/generator';
import { ITUNES_GENRES, LIST_GENRES, UNPLACED_GENRES } from '../../src/core/choreo/genreVocab.testutil';
import { readGenre, resolveSongStyle, styleLabel } from '../../src/core/choreo/songStyle';

const cell = (s: string) => s.replace(/\|/g, '/');
function row(name: string, source: string): string {
  const r = readGenre(name);
  if (!r.placed) return `| ${cell(name)} | ${source} | (not placed: ignored) | | | | | | |`;
  const s = resolveSongStyle(source === 'iTunes tag' ? { genre: name } : { genres: [name] });
  const fam = Object.entries(s.families).sort((a, b) => (b[1] ?? 0) - (a[1] ?? 0)).slice(0, 2).map(([f, w]) => `${f} ${(w ?? 0).toFixed(2)}`).join(', ');
  const subs = Object.entries(r.subs).map(([k, v]) => `${k} ${(v ?? 0).toFixed(2)}`).join(', ');
  const hint = [r.calm !== null ? `calm ${r.calm}` : '', r.soft !== null ? `soft ${r.soft}` : '', r.bpm ? `${r.bpm} BPM` : ''].filter(Boolean).join(', ');
  return `| ${cell(name)} | ${source} | ${cell(styleLabel(s))} | ${fam} | ${subs} | ${[...r.themes].join(', ')}${r.lively ? `${r.lively} when lively` : ''}${r.bright ? `${r.bright} when bright` : ''}${r.scene ? ` scene ${r.scene}` : ''} | ${r.still ? 'not dance music' : ''} | ${hint} | ${[...styleGenres(s)].join(', ') || '-'} |`;
}

console.log('# Genre vocabulary: what each name maps to (songStyle.ts)\n');
console.log('Generated by `npx tsx tools/eval/genreTable.ts`. "Sets opened" is for the name alone, without audio traits (the audio then decides the character: calm closes showpiece sets, opens lyrical).\n');
console.log('| Name | Source | Label | Leading families | Sub-styles | Themes | Kind | Hints | Sets opened |');
console.log('|---|---|---|---|---|---|---|---|---|');
for (const g of ITUNES_GENRES) console.log(row(g, 'iTunes tag'));
for (const g of LIST_GENRES) console.log(row(g, 'list name'));
for (const g of UNPLACED_GENRES) console.log(row(g, 'list name'));
